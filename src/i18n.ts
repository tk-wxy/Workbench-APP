export function makeT(lang: Lang) {
  return (zh: string, vars?: Record<string, string | number>): string => {
    let s = lang === "en" ? (EN_DICT[zh] ?? zh) : zh;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}
